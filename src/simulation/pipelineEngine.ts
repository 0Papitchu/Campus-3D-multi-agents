export function computeAgentOpsMetrics(
  pipelines: MultiAgentPipeline[],
  traces: AgentOpsTrace[]
): AgentOpsMetrics {
  const completedCount = pipelines.filter((p) => p.status === 'completed').length;
  const activeCount = pipelines.filter((p) => p.status === 'running').length;

  const totalTokens = traces.reduce((acc, t) => acc + t.tokens, 142800);
  const estimatedCost = (totalTokens / 1000000) * 0.18; // approx $0.18 per 1M tokens

  const avgLatency =
    traces.length > 0
      ? Math.round(traces.reduce((acc, t) => acc + t.durationMs, 0) / traces.length)
      : 480;

  const poleTokenShare = {
    tech: 68400,
    carole: 34200,
    contenu: 28500,
    personnel: 11700,
  };

  const collaborationMatrix = [
    { fromPole: 'tech' as const, toPole: 'tech' as const, flowsCount: 42 },
    { fromPole: 'tech' as const, toPole: 'carole' as const, flowsCount: 28 },
    { fromPole: 'carole' as const, toPole: 'contenu' as const, flowsCount: 36 },
    { fromPole: 'contenu' as const, toPole: 'personnel' as const, flowsCount: 19 },
    { fromPole: 'personnel' as const, toPole: 'tech' as const, flowsCount: 24 },
  ];

  return {
    totalTokensConsumed: totalTokens,
    estimatedCostUsd: Number(estimatedCost.toFixed(3)),
    completedPipelinesCount: completedCount,
    activePipelinesCount: activeCount,
    averageLatencyMs: avgLatency,
    poleTokenShare,
    collaborationMatrix,
  };
}
